#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate temporary nginx deny rules for obvious scrapers.

Dry-run by default: prints candidate IPs and the evidence against them.
With ``--apply``, maintains a JSON state file of time-boxed bans and
rewrites an nginx include of ``deny`` directives. It never reloads
nginx and never touches the firewall itself; review and reload remain
a human action (or a supervised cron entry that runs ``nginx -t``
before reloading).

Example (review first):
    .venv/bin/python scripts/ban_scrapers.py /var/log/nginx/spinorama-dev.access.log

Apply with 24 h bans:
    .venv/bin/python scripts/ban_scrapers.py --apply \\
        --state /var/lib/spinorama/bans.json \\
        --output /etc/nginx/snippets/spinorama-banned.conf \\
        --allow 203.0.113.10 /var/log/nginx/access.log
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import time
from collections import Counter, defaultdict
from dataclasses import dataclass, field

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from analyze_access_log import classify, is_honeypot, parse_line, read_records, speaker_of

# Re-exported for tests and for the cron wrapper.
__all__ = ["Candidate", "Thresholds", "find_candidates", "main", "parse_line"]


@dataclass(frozen=True)
class Thresholds:
    honeypot_hits: int = 1
    probe_hits: int = 3
    speaker_json: int = 20
    unique_speakers: int = 100
    total_requests: int = 5000


@dataclass
class Candidate:
    ip: str
    reasons: list[str] = field(default_factory=list)


def find_candidates(records, thresholds: Thresholds, allowlist: set[str]) -> list[Candidate]:
    honeypot: Counter[str] = Counter()
    probes: Counter[str] = Counter()
    speaker_json: Counter[str] = Counter()
    totals: Counter[str] = Counter()
    speakers: dict[str, set[str]] = defaultdict(set)
    for record in records:
        if record is None:
            continue
        totals[record.ip] += 1
        kind = classify(record)
        if kind == "honeypot":
            honeypot[record.ip] += 1
        elif kind == "probe":
            probes[record.ip] += 1
        elif kind == "speaker_json":
            speaker_json[record.ip] += 1
        name = speaker_of(record.path)
        if name:
            speakers[record.ip].add(name)

    candidates: dict[str, Candidate] = {}

    def add(ip: str, reason: str) -> None:
        if ip not in allowlist:
            candidates.setdefault(ip, Candidate(ip)).reasons.append(reason)

    for ip, count in honeypot.items():
        if count >= thresholds.honeypot_hits:
            add(ip, f"honeypot x{count}")
    for ip, count in probes.items():
        if count >= thresholds.probe_hits:
            add(ip, f"probes x{count}")
    for ip, count in speaker_json.items():
        if count >= thresholds.speaker_json:
            add(ip, f"speaker_json x{count}")
    for ip, names in speakers.items():
        if len(names) >= thresholds.unique_speakers:
            add(ip, f"unique_speakers x{len(names)}")
    for ip, count in totals.items():
        if count >= thresholds.total_requests:
            add(ip, f"total_requests x{count}")
    return sorted(candidates.values(), key=lambda c: c.ip)


def update_state(state_path: pathlib.Path, candidates: list[Candidate], now: float, ban_seconds: int) -> dict:
    try:
        state = json.loads(state_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        state = {}
    if not isinstance(state, dict):
        state = {}
    state = {ip: info for ip, info in state.items() if info.get("expires", 0) > now}
    for candidate in candidates:
        previous = state.get(candidate.ip, {})
        strikes = int(previous.get("strikes", 0)) + 1
        state[candidate.ip] = {
            "expires": now + ban_seconds * strikes,
            "strikes": strikes,
            "reasons": candidate.reasons,
        }
    state_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = state_path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8")
    tmp.replace(state_path)
    return state


def write_nginx_deny(output_path: pathlib.Path, state: dict) -> None:
    lines = ["# Generated by ban_scrapers.py; do not edit by hand.\n"]
    for ip in sorted(state):
        reasons = ", ".join(state[ip].get("reasons", []))
        lines.append(f"deny {ip}; # {reasons}\n")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = output_path.with_suffix(".conf.tmp")
    tmp.write_text("".join(lines), encoding="utf-8")
    tmp.replace(output_path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("logs", nargs="+")
    parser.add_argument("--apply", action="store_true", help="Write state and nginx deny include")
    parser.add_argument("--state", default="/var/lib/spinorama/bans.json")
    parser.add_argument("--output", default="/etc/nginx/snippets/spinorama-banned.conf")
    parser.add_argument("--ban-hours", type=int, default=24)
    parser.add_argument("--allow", action="append", default=[], help="IP to never ban")
    args = parser.parse_args(argv)

    records = read_records(args.logs)
    candidates = find_candidates(records, Thresholds(), allowlist=set(args.allow))
    for candidate in candidates:
        print(f"{candidate.ip}\t{'; '.join(candidate.reasons)}")
    if not args.apply:
        print(f"dry-run: {len(candidates)} candidate(s); rerun with --apply to write bans")
        return 0
    state = update_state(
        pathlib.Path(args.state), candidates, time.time(), args.ban_hours * 3600
    )
    write_nginx_deny(pathlib.Path(args.output), state)
    print(f"wrote {len(state)} active ban(s) to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
