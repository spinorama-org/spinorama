mkdir -p .cache
mkdir -p build/website
SECONDS=0
LOCK_DIR=.cache/update_website.lock

release_lock() {
    rm -f "$LOCK_DIR/pid"
    rmdir "$LOCK_DIR" 2>/dev/null || true
}

if ! mkdir "$LOCK_DIR" 2>/dev/null; then
    lock_pid=""
    if [ -f "$LOCK_DIR/pid" ]; then
        lock_pid=$(cat "$LOCK_DIR/pid")
    fi
    case "$lock_pid" in
        ''|*[!0-9]*) ;;
        *)
            if kill -0 "$lock_pid" 2>/dev/null; then
                echo "Another update_website.sh run is active (PID $lock_pid); refusing to overlap it."
                exit 1
            fi
            ;;
    esac
    if ! rmdir "$LOCK_DIR" 2>/dev/null || ! mkdir "$LOCK_DIR" 2>/dev/null; then
        echo "Cannot acquire $LOCK_DIR; remove the stale lock only after confirming no update is running."
        exit 1
    fi
fi
printf '%s\n' "$$" > "$LOCK_DIR/pid"
trap release_lock EXIT
trap 'exit 130' HUP INT TERM

elapsed_status() {
    local elapsed=$SECONDS
    printf '%02d:%02d %s\n' "$((elapsed / 60))" "$((elapsed % 60))" "$1"
}

elapsed_status "Update starts"

# Usage: ./update_website.sh [dev|prod] [--force] [--limit N]
#                             [--skip-build] [--skip-deploy]
# Default target is dev. Speaker graphs are generated by the Rust
# generate-graph binary (GPUI rendering + hardened WebP); radar and
# EQ-compare figures by the Rust generate-radar / generate-eq-compare
# binaries; headphone metadata, graphs and EQs by the Rust
# generate-headphone-meta / generate-headphone-graph /
# generate-peq-headphone binaries. Remaining steps stay in Python.
# Binaries for the servers
# are deployed separately by scripts/deploy_binaries.sh.
SITE_TARGET=dev
FORCE_FLAG=""
LIMIT_FLAG=""
SKIP_BUILD=0
SKIP_DEPLOY=0
while [ $# -gt 0 ]; do
    case "$1" in
        dev|prod) SITE_TARGET=$1 ;;
        --force) FORCE_FLAG="--force" ;;
        --limit) shift; LIMIT_FLAG="--limit $1" ;;
        --skip-build) SKIP_BUILD=1 ;;
        --skip-deploy) SKIP_DEPLOY=1 ;;
        *) echo "Unknown argument: $1" >&2; exit 2 ;;
    esac
    shift
done
elapsed_status "Target: $SITE_TARGET"

export CARGO_HOME=${CARGO_HOME:-/Volumes/home_tmp/tmp/cargo-home}
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-/Volumes/home_worktrees/spinorama-workspace-target}
GENERATE_GRAPH="$CARGO_TARGET_DIR/release/generate-graph"
GENERATE_RADAR="$CARGO_TARGET_DIR/release/generate-radar"
GENERATE_EQ_COMPARE="$CARGO_TARGET_DIR/release/generate-eq-compare"
GENERATE_HEADPHONE_META="$CARGO_TARGET_DIR/release/generate-headphone-meta"
GENERATE_HEADPHONE_GRAPH="$CARGO_TARGET_DIR/release/generate-headphone-graph"
GENERATE_PEQ_HEADPHONE="$CARGO_TARGET_DIR/release/generate-peq-headphone"

if [ -x .venv312/bin/python ]; then
    export THEPYTHON=.venv312/bin/python
elif [ -x .venv/bin/python ]; then
    export THEPYTHON=.venv/bin/python
else
    export THEPYTHON=python3.14
fi
export PYTHONPATH=src:src/website:src/spinorama:.

# check meta
${THEPYTHON} ./scripts/check_meta.py
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO checking metadata ($status)";
    exit 1;
else
    elapsed_status "OK checking metadata"
fi

# update logos and speakers picture
./scripts/update_pictures.sh
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after updating pictures ($status)"
    exit 1
else
    elapsed_status "OK after updating pictures"
fi

# build the Rust generators (and the GPUI renderer when its checkout
# is present)
if [ "$SKIP_BUILD" -eq 0 ]; then
    make generate-build
    status=$?
    if [ $status -ne 0 ]; then
        elapsed_status "KO building Rust generators ($status)"
        exit 1
    fi
    if [ -f /Volumes/home_tmp/src/gpui-toolkit/Cargo.toml ]; then
        cargo build --release \
            --manifest-path /Volumes/home_tmp/src/gpui-toolkit/Cargo.toml \
            -p gpui-spinorama --features capture-bench \
            --bin spinorama-render-images
        status=$?
        if [ $status -ne 0 ]; then
            elapsed_status "KO building GPUI renderer ($status)"
            exit 1
        fi
    fi
    elapsed_status "OK after building Rust generators"
else
    elapsed_status "SKIP building Rust generators"
fi
if [ ! -x "$GENERATE_GRAPH" ]; then
    elapsed_status "KO missing $GENERATE_GRAPH (run without --skip-build)"
    exit 1
fi

# validate the TOML catalogue consumed by the Rust batch modes
"$GENERATE_GRAPH" --metadata-dir datas/measurements --check-meta
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO checking TOML metadata ($status)"
    exit 1
else
    elapsed_status "OK after checking TOML metadata"
fi

# generate all speaker graphs with the Rust pipeline (incremental:
# existing outputs are skipped unless --force is given)
# shellcheck disable=SC2086
"$GENERATE_GRAPH" --metadata-dir datas/measurements \
    --data-dir . $FORCE_FLAG $LIMIT_FLAG --render-png --render-webp
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate graph!"
    exit 1;
else
    elapsed_status "OK after generate graph!"
fi

# recompute metadata for all speakers (Rust: loads measurements
# directly, ~3 s for the full catalogue; the Python version read the
# HDF5 cache and could silently go stale under the Rust pipeline)
GENERATE_META="$CARGO_TARGET_DIR/release/generate-meta"
"$GENERATE_META" --metadata-dir datas/measurements --output-dir dist/json
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate meta!"
    exit 1;
else
    elapsed_status "OK after generate meta!"
fi

# headphone metadata (Rust: parses the Python catalogue in datas/,
# no measurement cache needed)
"$GENERATE_HEADPHONE_META" --datas-dir ./datas --output-dir dist/json
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate headphone meta!"
    exit 1;
else
    elapsed_status "OK after generate headphone meta!"
fi

# fetch missing headphone pictures
#command=$(${THEPYTHON} ./scripts/headphone_fetch_pictures.py 2>&1)
#status=$?
#if [ $status -ne 0 ]; then
#    echo "WARN: headphone picture fetch had failures (non-fatal)"
#else
#    echo "OK after headphone picture fetch!"
#fi

# generate headphone graphs (Rust; reads the metadata JSON written
# by the generate-headphone-meta step above)
# shellcheck disable=SC2086
"$GENERATE_HEADPHONE_GRAPH" --headphones $FORCE_FLAG
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "WARN: headphone graph generation had failures (non-fatal)"
else
    elapsed_status "OK after headphone graph generation!"
fi

# compute headphone EQs (Rust optimizer; no external autoeq binary
# needed. Batch mode skips headphones whose EQ already exists unless
# --force is given, like the former shell script.)
if [ -x "$GENERATE_PEQ_HEADPHONE" ]; then
    # shellcheck disable=SC2086
    "$GENERATE_PEQ_HEADPHONE" --batch $FORCE_FLAG
    status=$?
    if [ $status -ne 0 ]; then
        elapsed_status "WARN: headphone EQ computation had failures (non-fatal)"
    else
        elapsed_status "OK after headphone EQ computation!"
    fi
else
    elapsed_status "SKIP headphone EQ computation ($GENERATE_PEQ_HEADPHONE not built)"
fi

# generate eq filters: filters_* pictures are emitted by the Rust
# generate-graph step above (GPUI renderer, origin directory). The
# Python scripts/generate_peqs.py --generate-images-only path (Plotly/
# Kaleido, hours for the catalogue) is no longer part of the pipeline;
# it remains available for ad-hoc regeneration.

# generate radar (Rust; --limit is not accepted by generate-radar)
# shellcheck disable=SC2086
"$GENERATE_RADAR" --data-dir . $FORCE_FLAG
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate radar!"
    exit 1;
else
    elapsed_status "OK after generate radar!"
fi

# generate eq_compare (Rust)
# shellcheck disable=SC2086
"$GENERATE_EQ_COMPARE" --data-dir . $FORCE_FLAG $LIMIT_FLAG
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate EQ compare!"
    exit 1;
else
    elapsed_status "OK after generate EQ compare!"
fi

# generate status
today="$(date "+%Y-%m-%d")"
${THEPYTHON} ./scripts/generate_stats.py --print=eq_csv --log-level=ERROR > build/spinorama.org-${today}.csv 2>&1
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate statistics in csv!"
    exit 1;
else
    elapsed_status "OK after generate statistics in csv!"
fi

# generate list of svgs
${THEPYTHON} ./scripts/svg2symbols.py > build/website/symbols.html
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after update symbols!"
    rm -f build/website/symbols.html
    exit 1;
else
    elapsed_status "OK after update symbols"
fi

# generate list of brands
./scripts/update_brands.sh
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after update brands!"
    rm -f build/website/brands.html
    exit 1;
else
    elapsed_status "OK after update brands"
fi

# generate list of reviewers
./scripts/update_reviewers.sh
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after update reviewers!"
    rm -f build/website/reviewers.html
    exit 1;
else
    elapsed_status "OK after update reviewers"
fi

if [ "$SITE_TARGET" = "prod" ]; then
    ${THEPYTHON} ./scripts/generate_html.py --optim
else
    ${THEPYTHON} ./scripts/generate_html.py --dev --optim --sitedev=https://dev.spinorama.org
fi
status=$?
if [ $status -ne 0 ]; then
    elapsed_status "KO after generate HTML!"
    exit 1;
else
    elapsed_status "OK after generate HTML!"
fi

# Build the manual before syncing dist. Copying its images alone leaves /docs
# without HTML, and rsync --delete can remove previously deployed manual pages.
if ! command -v quarto >/dev/null 2>&1; then
    elapsed_status "KO Quarto is required to build the manual before deployment"
    exit 1
fi
quarto render manual --to html
status=$?
if [ "$status" -ne 0 ]; then
    elapsed_status "KO after generating HTML manual ($status)"
    exit 1
fi
elapsed_status "OK after generating HTML manual"

#./scripts/check_html.sh
#status=$?
#if [ $status -ne 0 ]; then
#    elapsed_status "KO after checking HTML!"
#    exit 1;
#else
#    elapsed_status "OK after checking HTML!"
#fi

# copy
if [ "$SKIP_DEPLOY" -eq 1 ]; then
    elapsed_status "SKIP deploy to $SITE_TARGET"
elif [ "$SITE_TARGET" = "prod" ]; then
    ./scripts/update_prod_ovh.sh
    status=$?
    if [ $status -ne 0 ]; then
        elapsed_status "KO Update prod!"
        exit 1;
    else
        elapsed_status "OK Update prod!"
    fi
else
    ./scripts/update_dev.sh
    status=$?
    if [ $status -ne 0 ]; then
        elapsed_status "KO Update dev!"
        exit 1;
    else
        elapsed_status "OK Update dev!"
    fi
fi
elapsed_status "Update complete"
exit 0;
